import { supabaseAdmin } from '@/lib/supabaseAdmin';
import { COMMISSION_RATE } from '@/lib/finance';

// غيّر الإصدار لما تعدّل النص، فتحتاج كل المحلات توافق من جديد
export const AGREEMENT_VERSION = '1.0';
export const ACCEPT_MINUTES = 15;
export const PREP_MINUTES = 60;
export const LATE_PENALTY_JD = 1;
export const SETTLEMENT_DAYS = 7;
export const RETURN_HOURS = 48;

export function agreementClauses() {
  const pct = Math.round(COMMISSION_RATE * 100);
  return [
    [
      '1. المنتجات والأسعار والمخزون',
      'يلتزم المحل بدقة اسم المنتج وصوره وسعره وكميته ومقاساته وألوانه. أي تغيير (كمية، سعر، إيقاف منتج) يُبلَّغ للإدارة فوراً من المحادثة. وإذا تعذّر تجهيز منتج بعد الطلب يبلّغ المحل عبر زر "أبلّغ عن مشكلة"، والإدارة هي من تقرر الإلغاء أو البديل.',
    ],
    [
      '2. مهلة قبول الطلب',
      `يقبل المحل كل طلب جديد خلال ${ACCEPT_MINUTES} دقيقة من وصوله، خلال ساعات العمل المتفق عليها.`,
    ],
    [
      '3. مهلة التجهيز',
      `يجهّز المحل الطلب ويضغط "جاهز للاستلام" خلال ${PREP_MINUTES} دقيقة من قبوله، ويكتب رقم الطلب على الطرد بوضوح.`,
    ],
    [
      '4. التأخير والغرامات',
      `التأخير المتكرر عن المهلتين يخضع لتقييم الإدارة، ولها الحق بتحويل الطلب أو إلغاء الجزء المتأخر، وبخصم غرامة قدرها ${LATE_PENALTY_JD} دينار عن كل طلب يتأخر قبوله أو تجهيزه بأكثر من ضعف المهلة. وتظهر أرقام الالتزام ببطاقة أداء المحل.`,
    ],
    [
      '5. العمولة والتسوية',
      `عمولة المنصة ${pct}% من قيمة المنتجات المسلَّمة للزبون (دون رسوم التوصيل). تُسوّى مستحقات المحل كل ${SETTLEMENT_DAYS} أيام على الطرود المسلَّمة فقط، ويظهر كشف الحساب والدفعات بتطبيق المحل.`,
    ],
    [
      '6. الإرجاع والاستبدال',
      `يُقبل الإرجاع أو الاستبدال خلال ${RETURN_HOURS} ساعة من التسليم إذا كان المنتج تالفاً أو مخالفاً للطلب (منتج أو مقاس أو لون) بسبب المحل، بعد مراجعة الإدارة للصور. يتحمّل المحل كلفة الإرجاع وقيمة المنتج في هذه الحالات. وما يُستثنى من الإرجاع لأسباب صحية يُعلن بوصف المنتج.`,
    ],
    [
      '7. التغليف والجودة',
      'يفحص المحل جودة القطعة قبل التجهيز، ويغلّفها بشكل يحميها، ويضع رقم الطلب عليها.',
    ],
    [
      '8. الخصوصية وسرّية الزبائن',
      'لا يتواصل المحل مع الزبون مباشرة ولا يطلب بياناته، ولا يستخدم أي معلومة عن الزبائن خارج المنصة. التواصل مع الزبائن يتم عبر الإدارة فقط.',
    ],
    [
      '9. الإيقاف والإنهاء',
      'لأي طرف إنهاء الاتفاقية بإشعار مسبق. وللمنصة إيقاف المحل مؤقتاً عند تكرار المخالفات أو شكاوى الجودة.',
    ],
  ];
}

// إذا الجدول مش موجود بنسمح للمحل يكمل ولا نقفله
export async function hasAccepted(storeId) {
  try {
    const { data, error } = await supabaseAdmin
      .from('store_agreements')
      .select('id')
      .eq('store_id', storeId)
      .eq('version', AGREEMENT_VERSION)
      .maybeSingle();
    if (error) return true;
    return !!data;
  } catch {
    return true;
  }
}
